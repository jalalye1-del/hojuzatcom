String _transliterateArabic(String value) {
  const letters = <String, String>{
    'ء': '',
    'آ': 'A',
    'أ': 'A',
    'ؤ': 'o',
    'إ': 'E',
    'ئ': 'e',
    'ا': 'a',
    'ب': 'b',
    'ة': 'a',
    'ت': 't',
    'ث': 'th',
    'ج': 'j',
    'ح': 'h',
    'خ': 'kh',
    'د': 'd',
    'ذ': 'dh',
    'ر': 'r',
    'ز': 'z',
    'س': 's',
    'ش': 'sh',
    'ص': 's',
    'ض': 'd',
    'ط': 't',
    'ظ': 'z',
    'ع': 'a',
    'غ': 'gh',
    'ـ': '',
    'ف': 'f',
    'ق': 'q',
    'ك': 'k',
    'ل': 'l',
    'م': 'm',
    'ن': 'n',
    'ه': 'h',
    'و': 'w',
    'ى': 'a',
    'ي': 'y',
    'ً': '',
    'ٌ': '',
    'ٍ': '',
    'َ': '',
    'ُ': '',
    'ِ': '',
    'ّ': '',
    'ْ': '',
    '،': ',',
    '؛': ';',
    '؟': '?',
  };
  final output = StringBuffer();
  for (final rune in value.runes) {
    final character = String.fromCharCode(rune);
    output.write(letters[character] ?? character);
  }
  return output.toString();
}

