bool get appIsEnglish => AppSession.currentLanguage == 'English';

TextDirection get localizedTextDirection =>
    appIsEnglish ? TextDirection.ltr : TextDirection.rtl;

/// A drop-in text widget that keeps legacy and control-panel strings in sync
/// with the selected application language. New screens can still call [l10n]
/// explicitly; applying it twice is harmless for already translated text.
class LocalizedText extends StatelessWidget {
  const LocalizedText(
    this.data, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.textScaler,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
  });

  final String data;
  final TextStyle? style;
  final StrutStyle? strutStyle;
  final TextAlign? textAlign;
  final TextDirection? textDirection;
  final Locale? locale;
  final bool? softWrap;
  final TextOverflow? overflow;
  final TextScaler? textScaler;
  final int? maxLines;
  final String? semanticsLabel;
  final TextWidthBasis? textWidthBasis;
  final TextHeightBehavior? textHeightBehavior;
  final Color? selectionColor;

  @override
  Widget build(BuildContext context) => ValueListenableBuilder<String>(
    valueListenable: AppSession.languageListenable,
    builder: (context, _, child) => material.Text(
      l10n(data),
      style: style,
      strutStyle: strutStyle,
      textAlign: textAlign,
      textDirection: textDirection,
      locale: locale,
      softWrap: softWrap,
      overflow: overflow,
      textScaler: textScaler,
      maxLines: maxLines,
      semanticsLabel: semanticsLabel == null ? null : l10n(semanticsLabel!),
      textWidthBasis: textWidthBasis,
      textHeightBehavior: textHeightBehavior,
      selectionColor: selectionColor,
    ),
  );
}

String l10n(String arabic, [String? english]) {
  if (!appIsEnglish) return arabic;
  if (english != null) return english;
  final exact = _english[arabic];
  if (exact != null) return exact;
  var translated = arabic;
  for (final phrase in _phraseTranslations) {
    translated = translated.replaceAll(phrase.$1, phrase.$2);
  }
  return _containsArabic(translated)
      ? _transliterateArabic(translated)
      : translated;
}

bool _containsArabic(String value) =>
    RegExp(r'[\u0600-\u06ff]').hasMatch(value);

